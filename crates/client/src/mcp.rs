//! `vf mcp`: a stdio MCP server for the AGENT REMOTE mode — the
//! counterpart of `vectorfs mcp` (server-side, in-process single-writer).
//! This process owns NO storage and takes NO lock: every tool call proxies
//! to a running `vectorfs serve` daemon over the same signed-HTTP
//! [`Connection`] every vf verb uses, so wire semantics, limits,
//! validation and error shapes are the SDK-over-HTTP path verbatim. What
//! the daemon's gate sees is exactly what `vf search` / `vf put` produce —
//! one signer, one canonicalization.
//!
//! Relationship to `vectorfs mcp` (design.md §5.8): same agent contract —
//! tool results are JSON strings carrying `schema_version`, failures come
//! back as tool ERROR results (never server crashes) with a
//! `{code, message, hint}` JSON body — but a different deployment shape:
//! the agent's machine runs `vf mcp` against a daemon anywhere the
//! endpoint points (remote, containerized, TLS), while `vectorfs mcp` IS
//! the writer on local storage. Tool sets overlap where the verbs overlap
//! (search / put_source / list_sources); the AWS data-plane tools
//! (query_vectors / put_vectors / …) stay server-side — vf's surface is
//! the file layer (appendix E.4).
//!
//! RAG loop (encoded in the tool descriptions): `search` is the entry —
//! the query text is embedded once per the bucket's configured embedders,
//! per-index rankings are merged, every hit carries `content.text` (the
//! chunk, usable as context directly) and `location.key` (the source
//! file, fetchable whole with `get_source_data`).

