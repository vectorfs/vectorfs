// ---------------------------------------------------------------------------
// process entry (`vf mcp`): resolve, probe (warn-only), serve over stdio
// ---------------------------------------------------------------------------

/// Outcome of a `vf mcp` run for the CLI to turn into an exit code.
#[derive(Debug)]
pub enum McpExit {
    Ok,
    /// Startup/stdio failure (connection-config problems exit earlier —
    /// the CLI resolves the Connection before calling this).
    Failed(String),
}

/// Run the MCP server over stdin/stdout, proxying every tool call to the
/// daemon through `conn`. This process holds NO lock (the daemon owns the
/// data; it enforces SigV4 on every call). NEVER prints to stdout (it is
/// the protocol channel); all diagnostics go to stderr.
pub async fn run(conn: Connection, mode: ToolsMode) -> McpExit {
    use rmcp::ServiceExt;

    let conn = Arc::new(conn);

    // startup probe, warn-only: the daemon may legitimately come up after
    // the agent session starts — tool calls surface a fresh
    // {code,message,hint} error each time until it does
    match conn.get_health().await {
        Ok(h) => eprintln!(
            "vf mcp: daemon healthy (version {})",
            h["version"].as_str().unwrap_or("?")
        ),
        Err(f) => eprintln!(
            "vf mcp: WARNING: daemon not healthy yet ({}) — tool calls will report \
             {{code,message,hint}} errors until it is",
            f.message
        ),
    }
    let mode_name = if mode == ToolsMode::Rw { "rw" } else { "ro" };
    eprintln!(
        "vf mcp: serving stdio MCP (tools={mode_name}, endpoint {}) — every call proxies over \
         signed HTTP; this process holds no lock",
        conn.endpoint()
    );

    let server = VfMcp::new(conn, mode);
    let service = match server.serve(rmcp::transport::stdio()).await {
        Ok(s) => s,
        Err(e) => return McpExit::Failed(format!("stdio serve failed: {e}")),
    };
    // graceful end = the client closed stdin (waiting(), consumes the service)
    match service.waiting().await {
        Ok(reason) => eprintln!("vf mcp: session ended ({reason:?})"),
        Err(e) => eprintln!("vf mcp: session error: {e}"),
    }
    McpExit::Ok
}

