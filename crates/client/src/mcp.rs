/// Wrap a result as a successful tool result (JSON text content).
fn ok_result(v: serde_json::Value) -> CallToolResult {
    CallToolResult::success(vec![ContentBlock::text(v.to_string())])
}

fn tool_error(text: String) -> CallToolResult {
    CallToolResult::error(vec![ContentBlock::text(text)])
}

/// A tool-argument-level failure the wire never sees (path/content misuse,
/// unreadable local file): `{code: "Validation", …}`.
fn validation_error(message: String, hint: &str) -> String {
    json!({
        "code": "Validation",
        "message": message,
        "hint": hint,
    })
    .to_string()
}

/// Map a wire/transport failure onto the agent-facing `{code, message,
/// hint}` JSON string — the CLI's EXACT [`CallError::to_failure`] mapping,
/// so codes and hints match `vf` verbatim (ENDPOINT_UNREACHABLE,
/// AccessDenied, …).
fn wire_error(e: CallError, endpoint: &str) -> String {
    let f = e.to_failure(endpoint);
    json!({
        "code": f.code,
        "message": f.message,
        "hint": f.hint,
    })
    .to_string()
}

