/// Tool access modes for `vf mcp --tools`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
#[value(rename_all = "lowercase")]
pub enum ToolsMode {
    /// search / list_buckets / list_sources / get_source /
    /// get_source_data / status only.
    Ro,
    /// read-only set + put_source / delete_source / reindex (the default —
    /// the point of agent mode is that the agent can ingest; the daemon's
    /// gate still enforces SigV4 on every proxied call).
    Rw,
}

fn default_true() -> bool {
    true
}

fn default_top_k() -> i64 {
    10
}

