#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct SearchParams {
    /// Vector bucket to search (must have an [ingest.<bucket>] section on
    /// the daemon — list them with list_buckets).
    pub bucket: String,
    /// Query text.
    pub text: String,
    /// Results to return, 1..=1000.
    #[serde(default = "default_top_k")]
    pub top_k: i64,
    /// Optional metadata filter ($-operator syntax, same operator set as
    /// the daemon's QueryVectors: $eq $ne $gt $gte $lt $lte $startsWith
    /// $in $nin $exists $and $or; a bare value is an implicit $eq). ONE
    /// key differs between the two faces: `x-vf-src-name` ($eq/$in/bare
    /// value — filter by source FILE key, no hash digging) is translated
    /// server-side on this search face, while the same filter sent to
    /// query_vectors is a 400 (the key is non-filterable on the protocol
    /// face — filter x-vf-src-uri there).
    #[serde(default)]
    pub filter: Option<serde_json::Value>,
    /// Include each hit's stored chunk text (default true).
    #[serde(default = "default_true")]
    pub return_text: bool,
    /// Terminal view ordering (T18): "section-asc" / "section-desc" —
    /// re-order the final hits by (section, line, score desc, key asc),
    /// missing sections last; presentation only (scores keep their
    /// meaning, membership untouched). Absent = retrieval order.
    /// BACKLOG NOTE: this face deliberately gains ONLY orderBy — its
    /// searchMode/includeKinds/anchors arrears stay open (design D-10.4,
    /// the MCP 面欠账 backlog).
    #[serde(default)]
    pub order_by: Option<String>,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct ListSourcesParams {
    /// Vector bucket (see list_buckets for the ingest-configured names).
    pub bucket: String,
    /// Only keys starting with this prefix (filtered client-side).
    #[serde(default)]
    pub prefix: Option<String>,
    /// Only this status (PENDING / IN_PROGRESS / PARTIALLY_INDEXED /
    /// INDEXED / FAILED / DELETING).
    #[serde(default)]
    pub status: Option<String>,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct GetSourceParams {
    /// Vector bucket.
    pub bucket: String,
    /// Object key (see list_sources).
    pub key: String,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct GetSourceDataParams {
    /// Vector bucket.
    pub bucket: String,
    /// Object key of the source file (a search hit's location.key).
    pub key: String,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct PutSourceParams {
    /// Vector bucket (must have an [ingest.<bucket>] section on the daemon).
    pub bucket: String,
    /// LOCAL file path to upload (this process reads it and uploads the
    /// bytes; key defaults to the file's name). Mutually exclusive with
    /// content.
    #[serde(default)]
    pub path: Option<String>,
    /// Inline text stored as the object body (no filesystem round trip —
    /// for agent-generated content; key is then REQUIRED). Mutually
    /// exclusive with path.
    #[serde(default)]
    pub content: Option<String>,
    /// Object key (default with path: the file's name; REQUIRED with
    /// content).
    #[serde(default)]
    pub key: Option<String>,
    /// Foreground wait budget in seconds for a terminal status
    /// (INDEXED / PARTIALLY_INDEXED / FAILED); 0 (the default) returns as
    /// soon as the daemon accepts the upload.
    #[serde(default)]
    pub wait_seconds: u64,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct DeleteSourceParams {
    /// Vector bucket.
    pub bucket: String,
    /// Object key to delete (idempotent).
    pub key: String,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct ReindexParams {
    /// Vector bucket to re-embed completely.
    pub bucket: String,
}

