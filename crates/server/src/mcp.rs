/// Extract a JSON handler response body (`Json(...)` handlers only — the
/// write tools return 200-empty and never call this).
async fn response_json(resp: Response) -> Result<serde_json::Value, String> {
    let bytes = axum::body::to_bytes(resp.into_body(), crate::MAX_BODY)
        .await
        .map_err(|e| format!("reading tool response: {e}"))?;
    if bytes.is_empty() {
        return Ok(serde_json::Value::Null);
    }
    serde_json::from_slice(&bytes).map_err(|e| format!("parsing tool response: {e}"))
}

/// Map an ops error to the agent-facing `{code, message, hint}` JSON string
/// (report.rs contract; Validation/NotFound/Conflict etc. become tool ERROR
/// results, the server itself never crashes on them).
fn error_json(e: &ApiError) -> String {
    let (code, hint) = match e.shape {
        "ValidationException" => (
            "Validation",
            "fix the arguments (check limits in the tool descriptions: topK<=10000, batch<=500, \
             keys<=100/500, dimension must match the index — see list_indexes); the file-layer \
             tools (search/put_source/list_sources) need an [ingest.<bucket>] section \
             (see `vectorfs pipelines check`)",
        ),
        "NotFoundException" => (
            "NotFound",
            "verify the names with list_vector_buckets / list_indexes",
        ),
        "ConflictException" => (
            "Conflict",
            "the resource state changed; re-check with list tools and retry (writes are idempotent upserts)",
        ),
        _ => (
            "Internal",
            "this is a vectorfs bug or a corrupt dataset — run vectorfs doctor; if healthy, please report it",
        ),
    };
    json!({
        "code": code,
        "message": e.message,
        "hint": hint,
    })
    .to_string()
}

/// Wrap an impl result as a successful tool result (JSON text content).
fn ok_result(v: serde_json::Value) -> CallToolResult {
    CallToolResult::success(vec![ContentBlock::text(v.to_string())])
}

