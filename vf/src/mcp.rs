#[derive(Clone)]
pub struct VfMcp {
    state: Arc<AppState>,
    tool_router: ToolRouter<Self>,
}

impl VfMcp {
    /// `rw` = advertise the write tools too; `ro` disables them (hidden from
    /// tools/list AND rejected by tools/call — rmcp's ToolRouter keeps a
    /// disabled set for exactly this).
    pub fn new(state: Arc<AppState>, mode: ToolsMode) -> Self {
        let mut router = Self::tool_router();
        if mode == ToolsMode::Ro {
            router.disable_route("put_vectors");
            router.disable_route("delete_vectors");
        }
        VfMcp {
            state,
            tool_router: router,
        }
    }
}

#[tool_router(router = tool_router)]
impl VfMcp {
    /// List every vector bucket in this data root, sorted by name.
    #[tool(
        description = "List all vector buckets in the data root, sorted by name. Returns {schema_version, buckets:[{name, arn, creationTime}]}."
    )]
    async fn list_vector_buckets(&self) -> CallToolResult {
        match self.call_list_vector_buckets().await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    /// List the indexes of one bucket, sorted by name.
    #[tool(
        description = "List the indexes of one vector bucket, sorted by name. Returns {schema_version, bucket, indexes:[{name, dimension, distanceMetric, dataType, arn, creationTime}]} — use dimension/distanceMetric before put/query. Possible errors: {code:NotFound} when the bucket does not exist."
    )]
    async fn list_indexes(&self, p: Parameters<ListIndexesParams>) -> CallToolResult {
        match self.call_list_indexes(p.0.bucket).await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    /// KNN query with optional pre-filter.
    #[tool(
        description = "Query the k nearest neighbors of a vector, optionally pre-filtered by metadata (filter runs BEFORE the KNN — full recall). query_vector length must equal the index dimension (see list_indexes); topK 1..=10000 (results page at 100 — pass nextToken back with identical topK/queryVector/filter); filter operators: $eq $ne $gt $gte $lt $lte $startsWith $in $nin $exists $and $or, bare values are implicit $eq. Results are sorted by distance asc, key asc; every hit carries its distance. Errors are {code,message,hint} (Validation / NotFound)."
    )]
    async fn query_vectors(&self, p: Parameters<QueryVectorsParams>) -> CallToolResult {
        match self.call_query_vectors(p.0).await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    /// Fetch stored vectors by key.
    #[tool(
        description = "Fetch stored vectors by exact key (1..=100 keys; missing keys are simply omitted). Sorted by key asc. returnData/returnMetadata default true. Errors are {code,message,hint} (Validation / NotFound)."
    )]
    async fn get_vectors(&self, p: Parameters<GetVectorsParams>) -> CallToolResult {
        match self.call_get_vectors(p.0).await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    /// Upsert a batch of vectors (rw only).
    #[tool(
        description = "Insert or replace vectors (write tool — only present with --tools rw). Upsert semantics per key: an existing key's row is replaced WHOLE; omitting metadata CLEARS it. 1..=500 vectors per call, keys 1..=1024 chars, metadata <=50 keys / <=40KB total (<=2KB filterable). A metadata key's type (string/number/boolean/list) cannot change within an index. Idempotent: re-putting the same batch is safe. Errors are {code,message,hint} (Validation / NotFound)."
    )]
    async fn put_vectors(&self, p: Parameters<PutVectorsParams>) -> CallToolResult {
        match self.call_put_vectors(p.0).await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    /// Delete vectors by key (rw only).
    #[tool(
        description = "Delete vectors by exact key (write tool — only present with --tools rw). 1..=500 keys per call; deleting absent keys is a no-op (idempotent). Errors are {code,message,hint} (Validation / NotFound)."
    )]
    async fn delete_vectors(&self, p: Parameters<DeleteVectorsParams>) -> CallToolResult {
        match self.call_delete_vectors(p.0).await {
            Ok(v) => ok_result(v),
            Err(e) => tool_error(error_json(&e)),
        }
    }

    // ---- impls: thin adapters onto the ops handlers (the SDK path) ----

    /// The ops handlers take `State<AppState>`; clone out of the Arc (the
    /// state is Arc-heavy inside, so this is cheap).
    fn ops_state(&self) -> State<AppState> {
        State(self.state.as_ref().clone())
    }

    async fn call_list_vector_buckets(&self) -> Result<serde_json::Value, ApiError> {
        let resp = ops::list_vector_buckets(self.ops_state(), Bytes::from_static(b"{}")).await?;
        let v = response_json(resp).await.map_err(ops::ApiError::internal)?;
        let buckets: Vec<serde_json::Value> = v["vectorBuckets"]
            .as_array()
            .cloned()
            .unwrap_or_default()
            .iter()
            .map(|b| {
                json!({
                    "name": b["vectorBucketName"],
                    "arn": b["vectorBucketArn"],
                    "creationTime": b["creationTime"],
                })
            })
            .collect();
        Ok(json!({
            "schema_version": SCHEMA_VERSION,
            "buckets": buckets,
        }))
    }

    async fn call_list_indexes(&self, bucket: String) -> Result<serde_json::Value, ApiError> {
        let body = serde_json::to_vec(&WireBucketLocator {
            vector_bucket_name: bucket.clone(),
        })
        .expect("wire struct serializes");
        let resp = ops::list_indexes(self.ops_state(), Bytes::from(body)).await?;
        let v = response_json(resp).await.map_err(ops::ApiError::internal)?;
        // The wire ListIndexes emits the model's IndexSummary (name/arn/
        // creationTime only); agents need dimension/metric BEFORE building a
        // query, so enrich each row from the catalog's full index.json.
        let summaries: Vec<serde_json::Value> =
            v["indexes"].as_array().cloned().unwrap_or_default();
        let mut indexes = Vec::with_capacity(summaries.len());
        for ix in summaries {
            let name = ix["indexName"].as_str().unwrap_or_default().to_string();
            let full = self
                .state
                .storage
                .load_index(&bucket, &name)
                .await
                .ok()
                .flatten();
            indexes.push(json!({
                "name": name,
                "dimension": full.as_ref().map(|m| m.dimension),
                "distanceMetric": full.as_ref().map(|m| m.distance_metric.clone()),
                "dataType": full.as_ref().map(|m| m.data_type.clone()),
                "nonFilterableMetadataKeys": full.as_ref().and_then(|m| m.non_filterable_metadata_keys.clone()),
                "arn": ix["indexArn"],
                "creationTime": ix["creationTime"],
            }));
        }
        Ok(json!({
            "schema_version": SCHEMA_VERSION,
            "bucket": bucket,
            "indexes": indexes,
        }))
    }

    async fn call_query_vectors(
        &self,
        p: QueryVectorsParams,
    ) -> Result<serde_json::Value, ApiError> {
        let body = serde_json::to_vec(&WireQueryVectors {
            vector_bucket_name: p.bucket.clone(),
            index_name: p.index.clone(),
            top_k: p.top_k,
            query_vector: WireFloat32 {
                float32: p.query_vector.clone(),
            },
            filter: p.filter.clone(),
            return_distance: true, // agents want the score
            return_metadata: p.return_metadata,
            next_token: p.next_token.clone(),
        })
        .expect("wire struct serializes");
        let resp = ops::query_vectors(self.ops_state(), Bytes::from(body)).await?;
        let v = response_json(resp).await.map_err(ops::ApiError::internal)?;
        let mut out = json!({
            "schema_version": SCHEMA_VERSION,
            "bucket": p.bucket,
            "index": p.index,
            "distanceMetric": v["distanceMetric"],
            "vectors": v["vectors"],
        });
        if let Some(t) = v.get("nextToken").and_then(|t| t.as_str()) {
            out["nextToken"] = json!(t);
        }
        Ok(out)
    }

    async fn call_get_vectors(&self, p: GetVectorsParams) -> Result<serde_json::Value, ApiError> {
        // key-ascending determinism contract (the AWS face preserves request
        // order; for an agent tool the stable order is the better default)
        let mut keys = p.keys.clone();
        keys.sort();
        keys.dedup();
        let body = serde_json::to_vec(&WireGetVectors {
            vector_bucket_name: p.bucket.clone(),
            index_name: p.index.clone(),
            keys: keys.clone(),
            return_data: p.return_data,
            return_metadata: p.return_metadata,
        })
        .expect("wire struct serializes");
        let resp = ops::get_vectors(self.ops_state(), Bytes::from(body)).await?;
        let v = response_json(resp).await.map_err(ops::ApiError::internal)?;
        Ok(json!({
            "schema_version": SCHEMA_VERSION,
            "bucket": p.bucket,
            "index": p.index,
            "vectors": v["vectors"],
        }))
    }

    async fn call_put_vectors(&self, p: PutVectorsParams) -> Result<serde_json::Value, ApiError> {
        let body = serde_json::to_vec(&WirePutVectors {
            vector_bucket_name: p.bucket.clone(),
            index_name: p.index.clone(),
            vectors: p
                .vectors
                .iter()
                .map(|v| WirePutVector {
                    key: v.key.clone(),
                    data: WireFloat32 {
                        float32: v.vector.clone(),
                    },
                    metadata: v.metadata.clone().filter(|m| !m.is_null()),
                })
                .collect(),
        })
        .expect("wire struct serializes");
        // 200-empty on success. `stored` counts UNIQUE keys — ops resolves
        // same-batch duplicate keys before the engine (last one wins), so
        // the batch size would overcount what actually landed.
        let mut seen = std::collections::HashSet::new();
        let stored = p
            .vectors
            .iter()
            .filter(|v| seen.insert(v.key.clone()))
            .count();
        ops::put_vectors(self.ops_state(), Bytes::from(body)).await?;
        Ok(json!({
            "schema_version": SCHEMA_VERSION,
            "bucket": p.bucket,
            "index": p.index,
            "stored": stored,
        }))
    }

    async fn call_delete_vectors(
        &self,
        p: DeleteVectorsParams,
    ) -> Result<serde_json::Value, ApiError> {
        let body = serde_json::to_vec(&WireDeleteVectors {
            vector_bucket_name: p.bucket.clone(),
            index_name: p.index.clone(),
            keys: p.keys.clone(),
        })
        .expect("wire struct serializes");
        ops::delete_vectors(self.ops_state(), Bytes::from(body)).await?;
        Ok(json!({
            "schema_version": SCHEMA_VERSION,
            "bucket": p.bucket,
            "index": p.index,
            "deleted": true,
            "keysRequested": p.keys.len(),
        }))
    }
}

fn tool_error(text: String) -> CallToolResult {
    CallToolResult::error(vec![ContentBlock::text(text)])
}

