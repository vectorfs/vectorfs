#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct ListIndexesParams {
    /// Vector bucket name (list them with list_vector_buckets).
    pub bucket: String,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct QueryVectorsParams {
    /// Vector bucket name.
    pub bucket: String,
    /// Index name (see list_indexes for its dimension and metric).
    pub index: String,
    /// Query vector; its length must equal the index dimension.
    pub query_vector: Vec<f64>,
    /// Number of nearest neighbors to return; 1..=10000.
    pub top_k: i64,
    /// Optional metadata filter. Operator set (AWS S3 Vectors compatible):
    /// $eq $ne $gt $gte $lt $lte $startsWith $in $nin $exists $and $or.
    /// A bare value is an implicit $eq; multiple operators on one field AND
    /// together; metadata values may be string / number / boolean / list
    /// (lists match on any element for $eq/$in).
    #[serde(default)]
    pub filter: Option<serde_json::Value>,
    /// Include each hit's stored metadata (default true).
    #[serde(default = "default_true")]
    pub return_metadata: bool,
    /// Pagination token from a previous query_vectors response — results
    /// arrive in pages of 100; pass topK/queryVector/filter unchanged.
    #[serde(default)]
    pub next_token: Option<String>,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct GetVectorsParams {
    /// Vector bucket name.
    pub bucket: String,
    /// Index name.
    pub index: String,
    /// 1..=100 vector keys; missing keys are omitted from the response.
    pub keys: Vec<String>,
    /// Include the float32 vector data (default true).
    #[serde(default = "default_true")]
    pub return_data: bool,
    /// Include stored metadata (default true).
    #[serde(default = "default_true")]
    pub return_metadata: bool,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct PutVectorItem {
    /// Unique key of the vector (1..=1024 chars, case-sensitive UTF-8).
    pub key: String,
    /// Vector data; length must equal the index dimension.
    pub vector: Vec<f64>,
    /// Optional metadata object (string/number/boolean/flat-list values;
    /// ≤50 keys, ≤40KB total, ≤2KB filterable portion).
    #[serde(default)]
    pub metadata: Option<serde_json::Value>,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct PutVectorsParams {
    /// Vector bucket name.
    pub bucket: String,
    /// Index name.
    pub index: String,
    /// 1..=500 vectors. Upsert semantics: an existing key is replaced
    /// WHOLE (omitting metadata clears it).
    pub vectors: Vec<PutVectorItem>,
}

#[derive(Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct DeleteVectorsParams {
    /// Vector bucket name.
    pub bucket: String,
    /// Index name.
    pub index: String,
    /// 1..=500 vector keys; deleting absent keys is a no-op (idempotent).
    pub keys: Vec<String>,
}

