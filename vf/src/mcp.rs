    /// End-to-end stdio smoke (task T6): initialize handshake -> tools/list
    /// (rw set) -> tools/call, over an in-memory duplex pair — the same
    /// harness rmcp's own protocol tests use, no real process spawn.
    #[tokio::test]
    async fn e2e_initialize_list_tools_call() {
        use rmcp::ServiceExt as _;
        use rmcp::transport::{IntoTransport, Transport as _};

        let dir = tempfile::tempdir().unwrap();
        let s = seeded(dir.path()).await;
        // one vector to find
        vf_put(&s, "k1", vec![1.0, 0.0]).await;

        let (server_io, client_io) = tokio::io::duplex(8192);
        let handle = {
            let server = VfMcp::new(s, ToolsMode::Rw);
            tokio::spawn(async move { server.serve(server_io).await })
        };
        let mut client =
            IntoTransport::<rmcp::RoleClient, std::io::Error, _>::into_transport(client_io);

        // 1. initialize
        client
            .send(
                serde_json::from_str::<ClientJsonRpcMessage>(
                    r#"{"jsonrpc":"2.0","id":1,"method":"initialize","params":{
                    "protocolVersion":"2025-11-25","capabilities":{},
                    "clientInfo":{"name":"vf-test","version":"0"}}}"#,
                )
                .unwrap(),
            )
            .await
            .unwrap();
        let init = expect_response(&mut client).await;
        let ServerResult::InitializeResult(init) = init else {
            panic!("expected InitializeResult, got {init:?}");
        };
        assert_eq!(init.server_info.name, "vectorfs");
        assert_eq!(init.server_info.version, env!("CARGO_PKG_VERSION"));

        client
            .send(
                serde_json::from_str::<ClientJsonRpcMessage>(
                    r#"{"jsonrpc":"2.0","method":"notifications/initialized"}"#,
                )
                .unwrap(),
            )
            .await
            .unwrap();

        // 2. tools/list — all six, with descriptions and input schemas
        client
            .send(
                serde_json::from_str::<ClientJsonRpcMessage>(
                    r#"{"jsonrpc":"2.0","id":2,"method":"tools/list"}"#,
                )
                .unwrap(),
            )
            .await
            .unwrap();
        let ServerResult::ListToolsResult(list) = expect_response(&mut client).await else {
            panic!("expected ListToolsResult");
        };
        let names: Vec<&str> = list.tools.iter().map(|t| t.name.as_ref()).collect();
        assert_eq!(names.len(), 6, "{names:?}");
        for tool in &list.tools {
            assert!(
                tool.description.as_deref().is_some_and(|d| !d.is_empty()),
                "{} lacks a description",
                tool.name
            );
            assert!(
                !tool.input_schema.is_empty(),
                "{} lacks a schema",
                tool.name
            );
        }

        // 3. tools/call query_vectors — full JSON-RPC round trip
        client
            .send(
                serde_json::from_str::<ClientJsonRpcMessage>(
                    r#"{"jsonrpc":"2.0","id":3,"method":"tools/call","params":{
                    "name":"query_vectors","arguments":{
                        "bucket":"docs","index":"chunks","queryVector":[1.0,0.0],"topK":5}}}"#,
                )
                .unwrap(),
            )
            .await
            .unwrap();
        let ServerResult::CallToolResult(call) = expect_response(&mut client).await else {
            panic!("expected CallToolResult");
        };
        assert!(!call.is_error.unwrap_or(false));
        let text = match call.content.into_iter().next() {
            Some(rmcp::model::ContentBlock::Text(t)) => t.text,
            other => panic!("expected text content, got {other:?}"),
        };
        let v: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(v["schema_version"], SCHEMA_VERSION);
        assert_eq!(v["vectors"][0]["key"], "k1", "{v}");

        client.close().await.unwrap();
        handle.abort(); // duplex EOF ends the server too; abort is belt+braces
    }

    async fn vf_put(s: &Arc<AppState>, key: &str, vector: Vec<f64>) {
        let body = format!(
            r#"{{"vectorBucketName":"docs","indexName":"chunks","vectors":[{{"key":"{key}","data":{{"float32":{vector:?}}}}}]}}"#
        );
        ops::put_vectors(State(s.as_ref().clone()), Bytes::from(body))
            .await
            .unwrap();
    }

    async fn expect_response<T: rmcp::transport::Transport<rmcp::RoleClient>>(
        client: &mut T,
    ) -> ServerResult {
        match client.receive().await.expect("server response") {
            ServerJsonRpcMessage::Response(r) => r.result,
            other => panic!("expected a response, got {other:?}"),
        }
    }
